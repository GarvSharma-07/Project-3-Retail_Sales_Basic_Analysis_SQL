                        -- ( DATE EXPLORATION ) --
-- Activity 2 - Date Range Exploration
-- Q1. Determine the first and last order date and the total duration in months
Select 
	Min(Order_date)as First_Order,
	Max(Order_date)As Last_Order,
	DATEDIFF(month,Min(Order_date),Max(Order_date)) AS Total_Duration
	From Gold.fact_sales
-- Q2. Find the youngest and oldest customer based on birthdate
-- youngest customer--
Select * 
From Gold.dim_customers
Where birthdate =( select Min(Birthdate) from Gold.dim_customers )
-- oldest customer--
Select *
From Gold.dim_customers
Where birthdate =(select MAX(Birthdate) from Gold.dim_customers )
