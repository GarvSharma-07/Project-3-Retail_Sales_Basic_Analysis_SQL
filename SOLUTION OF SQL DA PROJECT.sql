                     -- ( MEASURES EXPLORATION ) --
-- Activity 3 - Measures Exploration (Key Metrics)
-- Q1. Find the Total Sales
Select Sum(sales_amount) As Total_Sales
From Gold.fact_sales

-- Q2. Find how many items are sold
Select Sum(quantity) as Item_solid From Gold.fact_sales

-- Q3. Find the average selling price
Select AVG(price) As AVG_Price From Gold.fact_sales

-- Q4. Find the Total number of Orders
Select Count(order_number) as No_Orders From Gold.fact_sales

-- Q5. Find the total number of products
Select Count(Distinct(Product_name)) As NO_Product From Gold.dim_products

-- Q6. Find the total number of customers
Select Count(Distinct(customer_id)) As NO_Customer From Gold.dim_customers

-- Q7. Find the total number of customers that has placed an order
Select Count(Distinct(customer_key)) As No_Customer_Placed_Order From Gold.fact_sales	

-- Q8. Generate a Report that shows all key metrics of the business
Select
Sum(sales_amount)As Total_Sales,
Sum(quantity) as Item_solid,
AVG(price)As AVG_Price,
Count(order_number)as No_Orders,
Count(Distinct(s.customer_key))As No_Customer_Placed_Order,
Count(Distinct(Product_name))As NO_Product,
Count(Distinct(customer_id))As NO_Customer
 From (Gold.dim_customers C
	Join Gold.fact_sales S on C.customer_key = S.customer_key 
	Join Gold.dim_products P on s.product_key = p.product_key
	)

