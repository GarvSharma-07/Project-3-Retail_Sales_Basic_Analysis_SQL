                           -- ( MAGNITUDE ) --
-- Activity 4 - Magnitude Analysis
-- Q1. Find total customers by countries.
Select country ,Count(Distinct(Customer_Key)) AS Total_Cutomer  From Gold.dim_customers
Group by country 

-- Q2. Find total customers by gender
Select gender ,Count(Distinct(Customer_Key)) AS Total_Cutomer  From Gold.dim_customers
Group by gender

-- Q3. Find total products by category
Select category ,Count(Distinct(product_key)) AS Total_product  From Gold.dim_products
Group by category

-- Q4. What is the average costs in each category?
Select category ,Avg(Cost) AS Avg_Cost  From Gold.dim_products
Group by category

-- Q5. What is the total revenue generated for each category?
Select category ,Sum(sales_amount) AS Total_Revenue 
From Gold.fact_sales S
Join Gold.dim_products P 
On S.product_key = P.product_key
Group by category

-- Q6. What is the total revenue generated by each customer?
Select customer_id,  Sum(sales_amount) AS Total_Revenue 
From Gold.fact_sales S
Join Gold.dim_customers C 
On S.customer_key = C.customer_key
Group by customer_id

-- Q7. What is the distribution of sold items across countries?
Select Country,Sum(Quantity) As Item_Sold
From Gold.dim_customers C
Join Gold.fact_sales S
ON C.customer_key = S.customer_key
Where country <> 'n/a'
Group by country

