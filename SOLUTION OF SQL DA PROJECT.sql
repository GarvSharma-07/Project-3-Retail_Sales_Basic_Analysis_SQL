                   -- ( CHANGE OVER TIME TRENDS ) --
-- Activity 5 - Analyze sales performance over time- Via Date Functions
-- Q1. Find the yearly & Monthly Sales with total customer count.
-- Years -- 
Select 
Year(Order_Date) AS Order_Year,
Month(Order_Date) AS Order_Months ,
Sum(Sales_Amount) As Total_Sales,
Count(Distinct customer_key) As Total_customer
From Gold.fact_sales
Where order_date is not null
Group by Year(order_date),Month(Order_Date)
Order by Year(order_date),Month(Order_Date)

-- Q2. Find the yearly & Monthly Sales with total customer count. (Using DATETRUNC)
Select 
Datetrunc(Year,Order_Date) AS Order_Year ,
Sum(Sales_Amount) As Total_Sales,
Count(Distinct(customer_key)) As Total_customer
From Gold.fact_sales
Where order_date is not null
Group by Datetrunc(Year,Order_Date)
Order by Datetrunc(Year,Order_Date)

-- Q3. Find the yearly & Monthly Sales with total customer count. FORMAT()
Select 
Format(Order_Date,'yyyy-MMMM') AS Order_Year ,
Sum(Sales_Amount) As Total_Sales,
Count(Distinct(customer_key)) As Total_customer
From Gold.fact_sales
Where order_date is not null
Group by Format(Order_Date,'yyyy-MMMM')
Order by Format(Order_Date,'yyyy-MMMM')

